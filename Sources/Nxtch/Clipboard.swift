import AppKit
import ImageIO

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    let kind: Kind
    var text: String?
    var imageFile: String?      // file name inside the Clipboard folder
    var paths: [String]?
    var sourceBundleID: String?
    var date: Date
    var pinned = false

    private var fileNames: [String] { (paths ?? []).map { ($0 as NSString).lastPathComponent } }

    var searchText: String {
        switch kind {
        case .text: return text ?? ""
        case .files: return fileNames.joined(separator: " ")
        case .image: return "Image"
        }
    }

    var preview: String {
        switch kind {
        case .text:
            // Every kind of line break shows, so nothing after a \r or U+2028 hides past the row's
            // one line (Return pastes all of it). Only the start is ever visible.
            return String((text ?? "").prefix(400)).trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "[\\r\\n\\x{0B}\\x{0C}\\x{85}\\x{2028}\\x{2029}]+", with: " ⏎ ", options: .regularExpression)
                .withoutInvisibles
        case .files: return fileNames.count == 1 ? fileNames[0] : "\(fileNames.count) files: \(fileNames.prefix(3).joined(separator: ", "))"
        case .image: return "Image"
        }
    }
}

/// Clipboard history. Checks the pasteboard's change count once a second (one integer read) and
/// records text, images and file references.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0
    /// Set briefly after copying, for the check mark.
    @Published private(set) var justCopied: UUID?
    /// Select mode: rows show a check box, and a click picks a row instead of copying it.
    @Published var selecting = false { didSet { if !selecting { picked = [] } } }
    @Published private(set) var picked: Set<UUID> = []

    var enabled = true
    /// Closes the notch, so focus goes back to the app a paste is for.
    var requestClose: (@MainActor () -> Void)?
    /// The app that was frontmost when the notch opened: where Return pastes to.
    var pasteTarget: pid_t?

    nonisolated static let unpinnedLimit = 100
    /// Unpinned items older than this are dropped, so a copied secret doesn't sit on disk forever.
    nonisolated static let maxAge: TimeInterval = 7 * 24 * 3600
    static let maxImageBytes = 20 * 1024 * 1024
    static let maxImagePixels = 50_000_000
    static let maxTextLength = 50_000
    /// Types password managers and similar tools put on items that must not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        // Universal Clipboard: what you copy on your phone isn't pulled onto this Mac's disk.
        "com.apple.is-remote-clipboard",
    ]
    /// Not every password manager marks its items, so nothing is recorded while one is in front.
    private static let ignoredApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.dashlane.dashlanephonefinal", "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop", "me.proton.pass.electron", "com.hicknhacksoftware.MacPass",
        "com.markmcguill.strongbox.mac", "com.callpod.keepermac.lite", "com.nordpass.macos.NordPass",
    ]

    private let storage = AppFiles.dir("Clipboard")
    /// Bundle ids of apps that came to the front since the last poll.
    private var activated: Set<String> = []
    private var historyURL: URL { storage.appendingPathComponent("history.json") }
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let thumbnails: NSCache<NSString, NSImage> = { let c = NSCache<NSString, NSImage>(); c.countLimit = 48; return c }()

    init() {
        let data = try? Data(contentsOf: historyURL)
        let saved = data.flatMap { try? JSONDecoder().decode([ClipItem].self, from: $0) }
        // The file could have been edited: an image name must be one nxtch made itself.
        items = (saved ?? []).filter { $0.imageFile == nil || imageURL($0.imageFile) != nil }
        expire()
        if data == nil || saved != nil { removeStrayImages() }
        // A password manager that was in front at any point since the last poll counts, not only
        // one still in front when the poll runs.
        NSWorkspace.shared.notificationCenter.addObserver(forName: NSWorkspace.didActivateApplicationNotification,
                                                          object: nil, queue: .main) { [weak self] note in
            let id = (note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication)?.bundleIdentifier
            MainActor.assumeIsolated { if let id { self?.activated.insert(id) } }
        }
        // Once a second: a changeCount read is cheap, and the wakeup is what costs.
        timer = .repeating(1, tolerance: 0.5) { [weak self] in self?.poll() }
    }

    /// Pinned first, then newest first, filtered by the search query.
    var visible: [ClipItem] {
        let base = query.isEmpty ? items : items.filter { $0.searchText.localizedCaseInsensitiveContains(query) }
        return base.filter(\.pinned) + base.filter { !$0.pinned }
    }

    /// Images history doesn't point at (nxtch quit before it saved) would otherwise never expire.
    private func removeStrayImages() {
        let kept = Set(items.compactMap(\.imageFile))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: storage.path)) ?? []
        for name in files where !kept.contains(name) {
            if let url = imageURL(name) { try? FileManager.default.removeItem(at: url) }
        }
    }

    /// Where a stored image lives. Only "<UUID>.png" is accepted, so a name can't point outside
    /// the Clipboard folder.
    private func imageURL(_ name: String?) -> URL? {
        guard let name, (name as NSString).pathExtension == "png",
              UUID(uuidString: (name as NSString).deletingPathExtension) != nil else { return nil }
        return storage.appendingPathComponent(name)
    }

    /// A small thumbnail for a row, decoded at row size rather than full size.
    func thumbnail(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile, let url = imageURL(name) else { return nil }
        if let cached = thumbnails.object(forKey: name as NSString) { return cached }
        let opts = [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 96] as CFDictionary
        guard let src = CGImageSourceCreateWithURL(url as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts) else { return nil }
        let img = NSImage(cgImage: cg, size: .zero)
        thumbnails.setObject(img, forKey: name as NSString)
        return img
    }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .files: pb.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let url = imageURL(item.imageFile), let data = try? Data(contentsOf: url) { pb.setData(data, forType: .png) }
        }
        lastChange = pb.changeCount   // don't record our own write
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
        justCopied = item.id
        after(1.2) { [weak self] in if self?.justCopied == item.id { self?.justCopied = nil } }
    }

    /// Copies, closes the notch so focus goes back to the app you were in, then presses ⌘V there.
    func paste(_ item: ClipItem) {
        Log.clipboard.info("paste kind=\(item.kind.rawValue, privacy: .public)")
        copy(item)
        let target = pasteTarget
        requestClose?()
        if let target { after(0.18) { Keystroke.paste(into: target) } }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func togglePick(_ item: ClipItem) {
        selecting = true
        if picked.remove(item.id) == nil { picked.insert(item.id) }
    }

    /// Deletes the picked entries, pinned ones included: picking one is asking for it by name.
    func deletePicked() {
        items.filter { picked.contains($0.id) }.forEach(deleteImage)
        items.removeAll { picked.contains($0.id) }
        selecting = false
        save()
    }

    func delete(_ item: ClipItem) {
        picked.remove(item.id)
        items.removeAll { $0.id == item.id }
        deleteImage(item)
        save()
    }

    /// Clears everything except pinned items.
    func clear() {
        selecting = false
        items.filter { !$0.pinned }.forEach(deleteImage)
        items.removeAll { !$0.pinned }
        save()
    }

    /// Drops items past their age limit. Run at launch and whenever the notch opens, so an old
    /// item goes even if nothing new has been copied since.
    func expire() { if trim() { save() } }

    func moveSelection(_ delta: Int) {
        selection = max(0, min(visible.count - 1, selection + delta))
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        let recent = activated
        activated = []
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard enabled, types.isDisjoint(with: Self.ignoredTypes), !Self.ignoredApps.contains(source ?? ""),
              recent.isDisjoint(with: Self.ignoredApps) else {
            Log.clipboard.info("skipped item (paused, concealed, or from a password manager)")
            return
        }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(ClipItem(id: UUID(), kind: .files, paths: urls.map(\.path), sourceBundleID: source, date: Date()))
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            // Each read copies the image across processes, so read it once.
            let pngData = pb.data(forType: .png)
            guard let data = pngData ?? pb.data(forType: .tiff), data.count <= Self.maxImageBytes,
                  let src = CGImageSourceCreateWithData(data as CFData, nil),
                  let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
                  let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int,
                  w > 0, h > 0, w <= Self.maxImagePixels / h,   // refuse decompression bombs before decoding (no w * h overflow)
                  let png = pngData ?? NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            else { return }
            let name = UUID().uuidString + ".png"
            guard pb.changeCount == lastChange, FileManager.default.createFile(atPath: storage.appendingPathComponent(name).path, contents: png,
                                                 attributes: [.posixPermissions: 0o600]) else { return }
            insert(ClipItem(id: UUID(), kind: .image, imageFile: name, sourceBundleID: source, date: Date()))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(id: UUID(), kind: .text, text: String(s.prefix(Self.maxTextLength)), sourceBundleID: source, date: Date()))
        }
    }

    private func insert(_ item: ClipItem) {
        // The types were checked a moment before the content was read. If something else was
        // copied in between (a password manager's concealed item), skip it: the next poll sees it.
        guard NSPasteboard.general.changeCount == lastChange else { return }
        Log.clipboard.info("captured kind=\(item.kind.rawValue, privacy: .public)")
        var item = item
        if item.kind != .image, let i = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.paths == item.paths }) {
            item.pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    /// Drops unpinned items that are too old or beyond the limit. Returns whether anything went.
    @discardableResult
    private func trim() -> Bool {
        let (kept, dropped) = Self.trimmed(items, now: Date())
        dropped.forEach(deleteImage)
        items = kept
        return !dropped.isEmpty
    }

    /// The rule itself: pinned items always stay. Unpinned ones go once they are older than
    /// `maxAge`, or once there are more than `unpinnedLimit` ahead of them (newest first).
    nonisolated static func trimmed(_ items: [ClipItem], now: Date) -> (kept: [ClipItem], dropped: [ClipItem]) {
        let cutoff = now.addingTimeInterval(-maxAge)
        var kept: [ClipItem] = [], dropped: [ClipItem] = [], unpinned = 0
        for item in items {
            if item.pinned { kept.append(item); continue }
            unpinned += 1
            if unpinned > unpinnedLimit || item.date < cutoff { dropped.append(item) } else { kept.append(item) }
        }
        return (kept, dropped)
    }

    private func deleteImage(_ item: ClipItem) {
        guard let name = item.imageFile, let url = imageURL(name) else { return }
        thumbnails.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: url)
    }

    /// One queue, so writes land in the order they were made.
    private static let saveQueue = DispatchQueue(label: "dev.nxtch.clipboard.save", qos: .utility)

    private func save() {
        let snapshot = items, url = historyURL
        Self.saveQueue.async {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: url, options: .atomic)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        }
    }
}
