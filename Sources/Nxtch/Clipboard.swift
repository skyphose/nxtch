import AppKit

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    let kind: Kind
    var text: String?
    var imageFile: String?      // file name inside the Clipboard storage folder
    var paths: [String]?
    var sourceBundleID: String?
    var date: Date
    var pinned = false

    var searchText: String {
        switch kind {
        case .text: return text ?? ""
        case .files: return (paths ?? []).map { ($0 as NSString).lastPathComponent }.joined(separator: " ")
        case .image: return "image"
        }
    }

    var preview: String {
        switch kind {
        case .text:
            return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
                .replacingOccurrences(of: "\n", with: " ⏎ ")
        case .files:
            let names = (paths ?? []).map { ($0 as NSString).lastPathComponent }
            return names.count == 1 ? names[0] : "\(names.count) files — \(names.prefix(3).joined(separator: ", "))"
        case .image: return "Image"
        }
    }

    func sameContent(as other: ClipItem) -> Bool {
        kind == other.kind && text == other.text && paths == other.paths && kind != .image
    }
}

/// Clipboard history. Polls the change count twice a second (a single integer read) and records
/// text, images and file references. Skips items password managers mark as concealed/transient.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0
    /// Set briefly after copying so the UI can show a check mark.
    @Published private(set) var justCopied: UUID?

    var enabled = true

    static let unpinnedLimit = 100
    static let maxImageBytes = 20 * 1024 * 1024
    static let maxTextLength = 200_000
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]

    private let storage = AppFiles.dir("Clipboard")
    private var historyURL: URL { storage.appendingPathComponent("history.json") }
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let imageCache: NSCache<NSString, NSImage> = { let c = NSCache<NSString, NSImage>(); c.countLimit = 24; return c }()

    init() {
        if let data = try? Data(contentsOf: historyURL),
           let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    /// Pinned first, then newest first; filtered by the search query.
    var visible: [ClipItem] {
        let base = query.isEmpty ? items : items.filter { $0.searchText.localizedCaseInsensitiveContains(query) }
        return base.filter(\.pinned) + base.filter { !$0.pinned }
    }

    func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let img = NSImage(contentsOf: storage.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(img, forKey: name as NSString)
        return img
    }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .files: pb.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image: if let img = image(for: item) { pb.writeObjects([img]) }
        }
        lastChange = pb.changeCount   // don't record our own write
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
        justCopied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            MainActor.assumeIsolated { if self?.justCopied == item.id { self?.justCopied = nil } }
        }
    }

    /// Copy, close the notch (focus returns to the app you were in), then press ⌘V there.
    /// Without Accessibility permission this just copies.
    func paste(_ item: ClipItem) {
        Log.clipboard.info("paste kind=\(item.kind.rawValue, privacy: .public)")
        copy(item)
        NotificationCenter.default.post(name: .nxtchRequestClose, object: nil)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) { Keystroke.paste() }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteImage(item)
        save()
    }

    /// Clears everything except pinned items.
    func clear() {
        items.filter { !$0.pinned }.forEach(deleteImage)
        items.removeAll { !$0.pinned }
        save()
    }

    func moveSelection(_ delta: Int) {
        let count = visible.count
        guard count > 0 else { return }
        selection = max(0, min(count - 1, selection + delta))
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled else { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else {
            Log.clipboard.info("skipped concealed/transient item")
            return
        }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            insert(ClipItem(id: UUID(), kind: .files, paths: urls.map(\.path), sourceBundleID: source, date: Date()))
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
                  let data = pb.data(forType: .png) ?? pb.data(forType: .tiff).flatMap(Self.pngData),
                  data.count <= Self.maxImageBytes {
            let name = UUID().uuidString + ".png"
            guard (try? data.write(to: storage.appendingPathComponent(name))) != nil else { return }
            insert(ClipItem(id: UUID(), kind: .image, imageFile: name, sourceBundleID: source, date: Date()))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(id: UUID(), kind: .text, text: String(s.prefix(Self.maxTextLength)),
                            sourceBundleID: source, date: Date()))
        }
    }

    private static func pngData(_ tiff: Data) -> Data? {
        NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private func insert(_ item: ClipItem) {
        Log.clipboard.info("captured kind=\(item.kind.rawValue, privacy: .public)")
        var item = item
        if let i = items.firstIndex(where: { $0.sameContent(as: item) }) {
            item.pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        // Trim oldest unpinned items beyond the limit.
        var unpinned = 0
        items = items.filter { i in
            if i.pinned { return true }
            unpinned += 1
            if unpinned > Self.unpinnedLimit { deleteImage(i); return false }
            return true
        }
        save()
    }

    private func deleteImage(_ item: ClipItem) {
        guard let name = item.imageFile else { return }
        imageCache.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: storage.appendingPathComponent(name))
    }

    private func save() {
        let snapshot = items
        let url = historyURL
        DispatchQueue.global(qos: .utility).async {
            if let data = try? JSONEncoder().encode(snapshot) { try? data.write(to: url, options: .atomic) }
        }
    }
}

extension Notification.Name {
    static let nxtchRequestClose = Notification.Name("nxtchRequestClose")
}
