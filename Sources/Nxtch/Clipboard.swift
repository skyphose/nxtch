import AppKit
import ImageIO

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image, files }

    let id: UUID
    let kind: Kind
    var text: String?
    var imageFile: String?      // file name inside the Clipboard folder
    var paths: [String]?
    var sourceBundleID: String?
    var date: Date
    var pinned = false

    private var fileNames: [String] { (paths ?? []).map { ($0 as NSString).lastPathComponent } }

    var searchText: String {
        switch kind {
        case .text: return text ?? ""
        case .files: return fileNames.joined(separator: " ")
        case .image: return "image"
        }
    }

    var preview: String {
        switch kind {
        case .text: return (text ?? "").trimmingCharacters(in: .whitespacesAndNewlines).replacingOccurrences(of: "\n", with: " ⏎ ")
        case .files: return fileNames.count == 1 ? fileNames[0] : "\(fileNames.count) files: \(fileNames.prefix(3).joined(separator: ", "))"
        case .image: return "Image"
        }
    }
}

/// Clipboard history. Checks the pasteboard's change count twice a second (one integer read) and
/// records text, images and file references.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published var query = "" { didSet { selection = 0 } }
    @Published var selection = 0
    /// Set briefly after copying, for the check mark.
    @Published private(set) var justCopied: UUID?

    var enabled = true
    /// The app that was frontmost when the notch opened: where Return pastes to.
    var pasteTarget: pid_t?

    static let unpinnedLimit = 100
    static let maxImageBytes = 20 * 1024 * 1024
    static let maxImagePixels = 50_000_000
    static let maxTextLength = 50_000
    /// Types password managers and similar tools put on items that must not be recorded.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
    ]
    /// Not every password manager marks its items, so nothing is recorded while one is in front.
    private static let ignoredApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "org.keepassxc.keepassxc", "com.dashlane.dashlanephonefinal", "com.lastpass.LastPass",
        "in.sinew.Enpass-Desktop", "me.proton.pass.electron",
    ]

    private let storage: URL = {
        var dir = AppFiles.dir("Clipboard")
        var values = URLResourceValues()
        values.isExcludedFromBackup = true      // keep copied secrets out of Time Machine
        try? dir.setResourceValues(values)
        return dir
    }()
    private var historyURL: URL { storage.appendingPathComponent("history.json") }
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let thumbnails: NSCache<NSString, NSImage> = { let c = NSCache<NSString, NSImage>(); c.countLimit = 48; return c }()

    init() {
        if let data = try? Data(contentsOf: historyURL), let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    /// Pinned first, then newest first, filtered by the search query.
    var visible: [ClipItem] {
        let base = query.isEmpty ? items : items.filter { $0.searchText.localizedCaseInsensitiveContains(query) }
        return base.filter(\.pinned) + base.filter { !$0.pinned }
    }

    /// A small thumbnail for a row, decoded at row size rather than full size.
    func thumbnail(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = thumbnails.object(forKey: name as NSString) { return cached }
        let opts = [kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 96] as CFDictionary
        guard let src = CGImageSourceCreateWithURL(storage.appendingPathComponent(name) as CFURL, nil),
              let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts) else { return nil }
        let img = NSImage(cgImage: cg, size: .zero)
        thumbnails.setObject(img, forKey: name as NSString)
        return img
    }

    // MARK: Actions

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .files: pb.writeObjects((item.paths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let name = item.imageFile, let data = try? Data(contentsOf: storage.appendingPathComponent(name)) { pb.setData(data, forType: .png) }
        }
        lastChange = pb.changeCount   // don't record our own write
        if let i = items.firstIndex(where: { $0.id == item.id }) {
            var moved = items.remove(at: i)
            moved.date = Date()
            items.insert(moved, at: 0)
            save()
        }
        justCopied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            MainActor.assumeIsolated { if self?.justCopied == item.id { self?.justCopied = nil } }
        }
    }

    /// Copies, closes the notch so focus goes back to the app you were in, then presses ⌘V there.
    func paste(_ item: ClipItem) {
        Log.clipboard.info("paste kind=\(item.kind.rawValue, privacy: .public)")
        copy(item)
        let target = pasteTarget
        NotificationCenter.default.post(name: .nxtchRequestClose, object: nil)
        if let target { DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) { Keystroke.paste(into: target) } }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        save()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        deleteImage(item)
        save()
    }

    /// Clears everything except pinned items.
    func clear() {
        items.filter { !$0.pinned }.forEach(deleteImage)
        items.removeAll { !$0.pinned }
        save()
    }

    func moveSelection(_ delta: Int) {
        selection = max(0, min(visible.count - 1, selection + delta))
    }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard enabled, types.isDisjoint(with: Self.ignoredTypes), !Self.ignoredApps.contains(source ?? "") else {
            Log.clipboard.info("skipped item (paused, concealed, or from a password manager)")
            return
        }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(ClipItem(id: UUID(), kind: .files, paths: urls.map(\.path), sourceBundleID: source, date: Date()))
        } else if types.contains(NSPasteboard.PasteboardType.png.rawValue) || types.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            guard let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), data.count <= Self.maxImageBytes,
                  let src = CGImageSourceCreateWithData(data as CFData, nil),
                  let props = CGImageSourceCopyPropertiesAtIndex(src, 0, nil) as? [CFString: Any],
                  let w = props[kCGImagePropertyPixelWidth] as? Int, let h = props[kCGImagePropertyPixelHeight] as? Int,
                  w * h <= Self.maxImagePixels,   // refuse decompression bombs before decoding
                  let png = pb.data(forType: .png) ?? NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
            else { return }
            let name = UUID().uuidString + ".png"
            guard FileManager.default.createFile(atPath: storage.appendingPathComponent(name).path, contents: png,
                                                 attributes: [.posixPermissions: 0o600]) else { return }
            insert(ClipItem(id: UUID(), kind: .image, imageFile: name, sourceBundleID: source, date: Date()))
        } else if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(id: UUID(), kind: .text, text: String(s.prefix(Self.maxTextLength)), sourceBundleID: source, date: Date()))
        }
    }

    private func insert(_ item: ClipItem) {
        Log.clipboard.info("captured kind=\(item.kind.rawValue, privacy: .public)")
        var item = item
        if item.kind != .image, let i = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.paths == item.paths }) {
            item.pinned = items[i].pinned
            items.remove(at: i)
        }
        items.insert(item, at: 0)
        // Trim the oldest unpinned items beyond the limit.
        var unpinned = 0
        items = items.filter { i in
            if i.pinned { return true }
            unpinned += 1
            if unpinned > Self.unpinnedLimit { deleteImage(i); return false }
            return true
        }
        save()
    }

    private func deleteImage(_ item: ClipItem) {
        guard let name = item.imageFile else { return }
        thumbnails.removeObject(forKey: name as NSString)
        try? FileManager.default.removeItem(at: storage.appendingPathComponent(name))
    }

    private func save() {
        let snapshot = items, url = historyURL
        DispatchQueue.global(qos: .utility).async {
            guard let data = try? JSONEncoder().encode(snapshot) else { return }
            try? data.write(to: url, options: .atomic)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        }
    }
}
